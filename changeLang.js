function changeLanguage(lang) {
    window.currentLanguage = lang;
    let objects = document.getElementsByClassName('langText');
    let objectsP = document.getElementsByClassName('langTextPlaceholder');
    const dict = languages[lang] || languages.en;

    for (let i = 0; i < objects.length; i++) {
        const key = objects[i].dataset.i18n || objects[i].id;
        const value = dict[key] || languages.en[key];
        if (value != null) objects[i].innerHTML = value;
    }

    for (let i = 0; i < objectsP.length; i++) {
        const key = objectsP[i].dataset.i18n || objectsP[i].id;
        const value = dict[key] || languages.en[key];
        if (value != null) objectsP[i].placeholder = value;
    }

    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

window.applyLanguage = function applyLanguage() {
    changeLanguage(window.currentLanguage || 'en');
};

// Helper function to get translated message with parameter substitution
function getMessage(key, params = {}) {
    const lang = window.currentLanguage;
    let message = languages[lang]?.[key] || languages['en']?.[key] || key;

    // Replace parameters in the message (all occurrences)
    Object.keys(params).forEach((param) => {
        const token = `{${param}}`;
        const value = params[param] == null ? '' : String(params[param]);
        if (message.includes(token)) {
            message = message.split(token).join(value);
        } else if (param === 'error' && value) {
            // Older templates were "Errore: " without {error} — still append the detail.
            message = `${message}${value}`;
        }
    });

    return message;
}

window.addEventListener('DOMContentLoaded', async () => {
    try {
        const savedLang = await ipcRenderer.invoke('get-language');
        window.currentLanguage = savedLang || 'en';
        changeLanguage(window.currentLanguage);
    } catch (_) {
        changeLanguage(window.currentLanguage || 'en');
    }
});

window.addEventListener('settingsUIReady', async () => {
    const selector = document.getElementById('languageSelector');
    if (!selector) return;

    const savedLang = window.currentLanguage || (await ipcRenderer.invoke('get-language'));
    selector.value = savedLang;
    changeLanguage(savedLang);

    if (selector.dataset.wired === '1') return;
    selector.dataset.wired = '1';
    selector.addEventListener('change', async (event) => {
        const selectedLang = event.target.value;
        await ipcRenderer.invoke('save-language', selectedLang);
        window.currentLanguage = selectedLang;
        changeLanguage(selectedLang);
    });
});

window.getMessage = getMessage;
window.changeLanguage = changeLanguage;
